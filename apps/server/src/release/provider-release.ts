// Provider release manifest (agents/release-process.md#provider-releases).
// The release workflow writes and signs it; hailctl verifies it with the pinned
// public key before trusting any image digest or bundle checksum.
import { createHash, createPrivateKey, createPublicKey, sign, verify, type KeyObject } from "node:crypto";
import { base58btc } from "multiformats/bases/base58";

export const RELEASE_TYPE = "hail.provider-release";
export const RELEASE_SIGNATURE_CONTEXT = "hail.provider-release.v2\0";
/** Files from apps/server/deploy/standalone shipped in every release bundle. */
export const BUNDLE_FILES = [".env.example", "Caddyfile", "Caddyfile.tunnel", "Caddyfile.web-client", "compose.tunnel.yaml", "compose.web-client.yaml", "compose.yaml", "README.md"] as const;
export const PLATFORMS = ["linux/amd64", "linux/arm64"] as const;
export type Platform = typeof PLATFORMS[number];

const VERSION = /^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/;
const DIGEST = /^sha256:[0-9a-f]{64}$/;
const COMMIT = /^[0-9a-f]{40}$/;
const REPOSITORY = /^ghcr\.io\/[a-z0-9._-]+(?:\/[a-z0-9._-]+)+$/;

export interface ReleaseImage {
  repository: string;
  /** Multi-platform index digest; Docker selects the host platform. */
  digest: string;
  platforms: Record<Platform, string>;
}
export interface ProviderRelease {
  type: typeof RELEASE_TYPE; version: 2;
  release: string; tag: string; commit: string;
  images: { provider: ReleaseImage; webClient: ReleaseImage };
  /** SHA-256 (hex) of each `hailctl-<os>-<arch>` binary in the release. */
  tools: { hailctl: Record<Platform, string> };
  bundle: { name: string; sha256: string };
  createdAt: string;
}

export function releaseTag(version: string): string {
  if (!VERSION.test(version)) throw new Error("Provider release versions are MAJOR.MINOR.PATCH");
  return `provider-v${version}`;
}

/** The release asset name of the hailctl binary for a platform. */
export function hailctlAsset(platform: Platform): string {
  return `hailctl-${platform.replace("/", "-")}`;
}

export function bundleName(version: string): string {
  releaseTag(version);
  return `hail-provider-${version}.tar.gz`;
}

/** `HAIL_*_IMAGE` pins written into the bundle, so its Compose files use exactly these images. */
export function releaseEnvironment(images: ProviderRelease["images"]): string {
  return `# Generated by the provider release; do not edit.\n` +
    `HAIL_PROVIDER_IMAGE=${images.provider.repository}@${images.provider.digest}\n` +
    `HAIL_WEB_CLIENT_IMAGE=${images.webClient.repository}@${images.webClient.digest}\n`;
}

export function checkRelease(value: unknown): asserts value is ProviderRelease {
  const fail = (): never => { throw new Error("Invalid provider release manifest"); };
  if (!value || typeof value !== "object" || Array.isArray(value)) fail();
  const row = value as Record<string, unknown>;
  if (Object.keys(row).join() !== "type,version,release,tag,commit,images,tools,bundle,createdAt" ||
    row.type !== RELEASE_TYPE || row.version !== 2 || typeof row.release !== "string" || !VERSION.test(row.release) ||
    row.tag !== `provider-v${row.release}` || typeof row.commit !== "string" || !COMMIT.test(row.commit) ||
    typeof row.createdAt !== "string" || Number.isNaN(Date.parse(row.createdAt))) fail();
  const images = row.images as Record<string, unknown>;
  if (!images || Object.keys(images).join() !== "provider,webClient") fail();
  for (const image of [images.provider, images.webClient] as Record<string, unknown>[]) {
    if (!image || Object.keys(image).join() !== "repository,digest,platforms" || typeof image.repository !== "string" ||
      !REPOSITORY.test(image.repository) || typeof image.digest !== "string" || !DIGEST.test(image.digest)) fail();
    const platforms = image.platforms as Record<string, unknown>;
    if (!platforms || Object.keys(platforms).join() !== PLATFORMS.join() ||
      PLATFORMS.some(platform => typeof platforms[platform] !== "string" || !DIGEST.test(platforms[platform] as string))) fail();
  }
  const tools = row.tools as Record<string, unknown>, hailctl = tools?.hailctl as Record<string, unknown>;
  if (!tools || Object.keys(tools).join() !== "hailctl" || !hailctl || Object.keys(hailctl).join() !== PLATFORMS.join() ||
    PLATFORMS.some(platform => typeof hailctl[platform] !== "string" || !/^[0-9a-f]{64}$/.test(hailctl[platform] as string))) fail();
  const bundle = row.bundle as Record<string, unknown>;
  if (!bundle || Object.keys(bundle).join() !== "name,sha256" || bundle.name !== bundleName(row.release as string) ||
    typeof bundle.sha256 !== "string" || !/^[0-9a-f]{64}$/.test(bundle.sha256)) fail();
}

/** The exact bytes that are signed and published. */
export function encodeRelease(release: ProviderRelease): Uint8Array {
  checkRelease(release);
  return new TextEncoder().encode(JSON.stringify(release, null, 2) + "\n");
}

function signingInput(bytes: Uint8Array): Uint8Array {
  const context = new TextEncoder().encode(RELEASE_SIGNATURE_CONTEXT);
  const input = new Uint8Array(context.length + bytes.length);
  input.set(context); input.set(bytes, context.length);
  return input;
}

export function publicDidKey(key: KeyObject): string {
  const raw = (key.type === "public" ? key : createPublicKey(key)).export({ format: "der", type: "spki" }).subarray(-32);
  return `did:key:${base58btc.encode(new Uint8Array([0xed, 0x01, ...raw]))}`;
}

/** PEM (SPKI) form of a pinned did:key, for verifiers such as openssl in install.sh. */
export function publicKeyPem(didKey: string): string {
  return publicKeyFromDid(didKey).export({ format: "pem", type: "spki" }).toString().trim();
}

function publicKeyFromDid(didKey: string): KeyObject {
  const decoded = didKey.startsWith("did:key:z") ? base58btc.decode(didKey.slice(8)) : new Uint8Array();
  if (decoded.length !== 34 || decoded[0] !== 0xed || decoded[1] !== 0x01) throw new Error("Expected an Ed25519 did:key");
  return createPublicKey({ format: "der", type: "spki",
    key: Buffer.concat([Buffer.from("302a300506032b6570032100", "hex"), decoded.subarray(2)]) });
}

/** Detached signature: unpadded base64url Ed25519 over the context-prefixed manifest bytes. */
export function signRelease(bytes: Uint8Array, privateKeyPem: string): string {
  const key = createPrivateKey(privateKeyPem);
  if (key.asymmetricKeyType !== "ed25519") throw new Error("The release signing key must be Ed25519");
  return Buffer.from(sign(null, signingInput(bytes), key)).toString("base64url");
}

/** Verifies and parses published manifest bytes against the pinned public key. */
export function verifyRelease(bytes: Uint8Array, signature: string, didKey: string): ProviderRelease {
  if (!/^[A-Za-z0-9_-]{86}$/.test(signature.trim()) ||
    !verify(null, signingInput(bytes), publicKeyFromDid(didKey), Buffer.from(signature.trim(), "base64url")))
    throw new Error("Provider release signature is invalid");
  const release: unknown = JSON.parse(new TextDecoder("utf-8", { fatal: true }).decode(bytes));
  checkRelease(release);
  if (!Buffer.from(encodeRelease(release)).equals(Buffer.from(bytes))) throw new Error("Provider release manifest is not canonical");
  return release;
}

export function sha256Hex(bytes: Uint8Array): string {
  return createHash("sha256").update(bytes).digest("hex");
}

/** The command for Haili's installed wrapper. It uses the amd64 images, as before multi-platform releases. */
export function hailiDeployCommand(release: ProviderRelease): string {
  const { provider, webClient } = release.images;
  return `hail-provider-ops deploy ${release.commit} ${provider.repository}@${provider.platforms["linux/amd64"]} ` +
    `${webClient.repository}@${webClient.platforms["linux/amd64"]}\n`;
}
